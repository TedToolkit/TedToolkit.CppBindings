using System.Text;

using TedToolkit.Occt.Generator.Models.Declarations;

namespace TedToolkit.Occt.Generator.Generators;

/// <summary>
/// Generates the process-lifetime native module and complete export table.
/// </summary>
internal static class NativeApiGenerator
{
    /// <summary>
    /// Gets the generated source file name.
    /// </summary>
    public const string FileName = "NativeApi.g.cs";

    /// <summary>
    /// Generates the complete native export table.
    /// </summary>
    /// <param name="records">The completed declaration models.</param>
    /// <param name="nativeLibraryBaseName">The validated native library basename.</param>
    /// <returns>The complete C# source.</returns>
    public static string Generate(IReadOnlyList<RecordModel> records, string nativeLibraryBaseName)
    {
        ArgumentNullException.ThrowIfNull(records);
        ArgumentException.ThrowIfNullOrEmpty(nativeLibraryBaseName);

        var exports = GetExports(records);
        var builder = new StringBuilder(
            "// <auto-generated />\n#pragma warning disable\n\n"
            + "using System.Runtime.InteropServices;\n\n"
            + "namespace TedToolkit.Occt;\n\n"
            + "internal static class NativeApi\n{\n"
            + "    private static readonly nint Module = NativeLibrary.Load(\"");
        _ = builder.Append(Escape(nativeLibraryBaseName))
            .Append("\", typeof(NativeApi).Assembly, null);\n\n");
        foreach (var export in exports)
        {
            _ = builder.Append("    internal static readonly nint ").Append(export)
                .Append(" = NativeLibrary.GetExport(Module, nameof(").Append(export).Append("));\n");
        }

        _ = builder.Append("}\n");
        return builder.ToString();
    }

    private static string[] GetExports(IReadOnlyList<RecordModel> records)
    {
        var exports = new HashSet<string>(StringComparer.Ordinal) { "NativeError_Clear", };
        foreach (var record in records.OrderBy(static value => value.Type.CSharpTypeName, StringComparer.Ordinal))
        {
            foreach (var method in record.MethodModels)
            {
                if (!exports.Add(method.NativeExportName))
                {
                    throw new InvalidOperationException($"Duplicate native export '{method.NativeExportName}'.");
                }
            }

            foreach (var relation in record.Bases.Where(static value =>
                         value.IsPublic
                         && value.PointerAdjustment is PointerAdjustmentKind.NativeAdjust))
            {
                var export = NativeExportNameBuilder.GetPointerAdjustmentName(record, relation.Base);
                if (!exports.Add(export))
                {
                    throw new InvalidOperationException($"Duplicate native export '{export}'.");
                }
            }
        }

        return exports.Order(StringComparer.Ordinal).ToArray();
    }

    private static string Escape(string value)
    {
        return value.Replace("\\", "\\\\", StringComparison.Ordinal)
            .Replace("\"", "\\\"", StringComparison.Ordinal);
    }
}