using System.Text;

namespace TedToolkit.CppBindings.Generator.Generators;

/// <summary>
/// Generates the single exported native function-table entry point.
/// </summary>
internal static class NativeFunctionTableGenerator
{
    /// <summary>
    /// Gets the generated source file name.
    /// </summary>
    public const string FileName = "NativeFunctionTable.cpp";

    /// <summary>
    /// Generates the native function table in the same deterministic order as managed loading.
    /// </summary>
    /// <param name="exports">The native function names.</param>
    /// <returns>The complete C++ source.</returns>
    public static string Generate(IReadOnlyList<string> exports)
    {
        ArgumentNullException.ThrowIfNull(exports);
        var builder = new StringBuilder("""
            // <auto-generated />
            #include <cstdint>

            #ifndef TEDTOOLKIT_CPPBINDINGS_EXPORT
            #if defined(_WIN32)
            #define TEDTOOLKIT_CPPBINDINGS_EXPORT __declspec(dllexport)
            #elif defined(__has_attribute)
            #if __has_attribute(visibility)
            #define TEDTOOLKIT_CPPBINDINGS_EXPORT __attribute__((visibility("default")))
            #endif
            #endif
            #endif
            #ifndef TEDTOOLKIT_CPPBINDINGS_EXPORT
            #define TEDTOOLKIT_CPPBINDINGS_EXPORT
            #endif
            """ + "\n\n");
        foreach (var export in exports)
        {
            _ = builder.Append("extern \"C\" void ").Append(export).Append("();\n");
        }

        _ = builder.Append(exports.Count is 0
            ? "\nstatic const std::uintptr_t Functions[1] =\n{\n"
            : "\nstatic const std::uintptr_t Functions[] =\n{\n");
        foreach (var export in exports)
        {
            _ = builder.Append("    reinterpret_cast<std::uintptr_t>(&").Append(export).Append("),\n");
        }

        _ = builder.Append(
            "};\n\nextern \"C\" TEDTOOLKIT_CPPBINDINGS_EXPORT const std::uintptr_t* "
            + "NativeApi_GetFunctionTable() noexcept\n{\n    return Functions;\n}\n");
        return builder.ToString();
    }
}