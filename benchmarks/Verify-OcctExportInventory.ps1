#Requires -Version 7.5

$ErrorActionPreference = 'Stop'
Set-StrictMode -Version Latest
$tool = Join-Path $PSScriptRoot 'Get-OcctExportInventory.ps1'
$repository = Split-Path $PSScriptRoot -Parent
$proofRoot = Join-Path $repository ('out/benchmark/export-proof-' + [Guid]::NewGuid().ToString('N'))
$null = [IO.Directory]::CreateDirectory($proofRoot)

function Write-Fixture {
    param([string] $Path, [string[]] $Symbols)

    $declarations = @($Symbols | ForEach-Object { "extern `"C`" void $_();" }) -join "`n"
    $slots = @($Symbols | ForEach-Object { "    reinterpret_cast<std::uintptr_t>(&$_)," }) -join "`n"
    [IO.File]::WriteAllText($Path, @"
// <auto-generated />
#include <cstdint>

$declarations

static const std::uintptr_t Functions[] =
{
$slots
};

extern "C" __declspec(dllexport) const std::uintptr_t* NativeApi_GetFunctionTable() noexcept
{
    return Functions;
}
"@, [Text.UTF8Encoding]::new($false))
}

$source = Join-Path $proofRoot 'NativeFunctionTable.cpp'
$reorderedSource = Join-Path $proofRoot 'NativeFunctionTable.reordered.cpp'
$duplicateSource = Join-Path $proofRoot 'NativeFunctionTable.duplicate.cpp'
$inventoryPath = Join-Path $proofRoot 'inventory.json'
$matchingPath = Join-Path $proofRoot 'matching.json'
$reorderedPath = Join-Path $proofRoot 'reordered.json'
$duplicatePath = Join-Path $proofRoot 'duplicate.json'
Write-Fixture $source @('Fixture_case', 'Fixture_Case')
Write-Fixture $reorderedSource @('Fixture_Case', 'Fixture_case')
Write-Fixture $duplicateSource @('Fixture_case', 'Fixture_case')

& $tool -SourcePath $source -ReportPath $inventoryPath
$inventory = Get-Content -LiteralPath $inventoryPath -Raw | ConvertFrom-Json
if ($inventory.ExportCount -ne 2 -or (@($inventory.Exports) -join ',') -cne 'Fixture_case,Fixture_Case') {
    throw 'Legitimate native symbols that differ only by case were lost or reordered.'
}

& $tool -SourcePath $source -ReportPath $matchingPath -CompareTo $inventoryPath
$matching = Get-Content -LiteralPath $matchingPath -Raw | ConvertFrom-Json
if (-not $matching.Comparison.EqualOrderedExports) { throw 'An exact ordered export inventory did not compare equal.' }

& $tool -SourcePath $reorderedSource -ReportPath $reorderedPath -CompareTo $inventoryPath
$reordered = Get-Content -LiteralPath $reorderedPath -Raw | ConvertFrom-Json
if ($reordered.Comparison.EqualOrderedExports) { throw 'Export order changes were not detected exactly.' }

$duplicateFailure = $null
try { & $tool -SourcePath $duplicateSource -ReportPath $duplicatePath }
catch { $duplicateFailure = $_.Exception.Message }
if ($duplicateFailure -notlike '*contains duplicate slots*' -or (Test-Path -LiteralPath $duplicatePath)) {
    throw 'An exact duplicate native symbol was accepted or produced evidence.'
}

Write-Output "OCCT export inventory proof passed: ordinal case-only symbols, exact ordering, and exact-duplicate rejection. Evidence: $proofRoot"
